-- ==============================================================================
-- 001_create_feedbacks_table.sql
-- 목적: 비로그인 익명 사용자를 위한 피드백 저장 테이블 및 RLS(행 단위 보안 정책) 설정
-- ==============================================================================

-- 1. feedbacks 테이블 생성
-- id: 고유 식별자 (자동 증가)
-- created_at: 생성 일시 (UTC 기준 기본값)
-- nickname: 작성자 닉네임 (필수)
-- rating: 별점 (1점 ~ 5점 사이의 정수, 제약 조건 적용)
-- content: 피드백 본문 내용 (필수)
CREATE TABLE IF NOT EXISTS feedbacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  nickname TEXT NOT NULL,
  rating INT CHECK (rating >= 1 AND rating <= 5) NOT NULL,
  content TEXT NOT NULL
);

-- 2. RLS (Row Level Security - 행 단위 보안) 활성화
ALTER TABLE feedbacks ENABLE ROW LEVEL SECURITY;

-- 3. 피드백 작성 정책: 로그인하지 않은 익명 사용자도 누구나 자유롭게 피드백을 등록(INSERT)할 수 있도록 허용
CREATE POLICY "누구나 피드백 작성 가능" ON feedbacks
  FOR INSERT WITH CHECK (true);

-- 4. 피드백 조회 정책: 모든 방문자가 등록된 피드백 목록을 최신순으로 읽기(SELECT)할 수 있도록 허용
CREATE POLICY "누구나 피드백 조회 가능" ON feedbacks
  FOR SELECT USING (true);

